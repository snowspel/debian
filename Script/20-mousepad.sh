#!/usr/bin/env bash
# snow-mousepad.sh : gives Mousepad (text area) the colours of your Snow theme.
#   Reads ~/.config/snow/state/theme.json (bg, surface, text, muted, accent, warn, danger, success), writes the colour scheme
#   ~/.local/share/gtksourceview-4/styles/snow.xml and selects it in Mousepad. Run it again after you change the Snow theme.
#   Also puts a small gap (GAP below, 8px = about one space) between the line numbers and the text (a marked block in ~/.config/gtk-3.0/gtk.css).
#   Undo: bash snow-mousepad.sh undo      (colour scheme + gap block are removed; menus / toolbar are never touched)
set -u
MODN="20-mousepad"
G=$'\e[32m'; Y=$'\e[33m'; R=$'\e[31m'; N=$'\e[0m'
ok() { echo "${G}[PASS]${N} $*"; }; wr() { echo "${Y}[WARN]${N} $*"; }; bad() { echo "${R}[FAIL]${N} $*"; }
[ "$(id -u)" -eq 0 ] && { echo "[PROBLEM] do not run as root"; exit 1; }
res() { [ -n "${SNOW_RESULTS:-}" ] && printf '%s|%s|%s|%s\n' "$1" "$MODN" "$2" "$3" >> "$SNOW_RESULTS"; return 0; }
P=0; W=0; F=0
chk() { # chk LEVEL message fix
  case "$1" in PASS) P=$((P+1)) ;; WARN) W=$((W+1)) ;; FAIL) F=$((F+1)) ;; esac
  case "$1" in PASS) echo "${G}PASS${N} $2" ;; WARN) echo "${Y}WARN${N} $2" ;; FAIL) echo "${R}FAIL${N} $2"; echo "[PROBLEM] $2" ;; esac; res "$1" "$2" "$3"; }

TJ="$HOME/.config/snow/state/theme.json"; DIR="$HOME/.local/share/gtksourceview-4/styles"; OUT="$DIR/snow.xml"
GAP=8   # pixels between line numbers and text
CSS="$HOME/.config/gtk-3.0/gtk.css"
SCHEMA=org.xfce.mousepad.preferences.view; KEY=color-scheme
have_gs() { command -v gsettings >/dev/null 2>&1 && gsettings list-schemas 2>/dev/null | grep -qx "$SCHEMA"; }

if [ "${1:-}" = check ]; then
echo; echo "== check $MODN: Editor: Mousepad (Snow colour scheme) =="
command -v mousepad >/dev/null 2>&1 && chk PASS "mousepad installed" "" || chk FAIL "mousepad is not installed" "bash ~/Snow/Script/20-mousepad.sh"
[ -s "$HOME/.local/share/gtksourceview-4/styles/snow.xml" ] && chk PASS "Mousepad colour scheme snow.xml exists" "" || chk WARN "Mousepad colour scheme snow.xml is missing" "bash ~/Snow/Script/20-mousepad.sh"
command -v gsettings >/dev/null 2>&1 && [ "$(gsettings get org.xfce.mousepad.preferences.view color-scheme 2>/dev/null)" = "'snow'" ] && chk PASS "Mousepad uses the snow colour scheme" "" || chk WARN "Mousepad does not use the snow colour scheme" "bash ~/Snow/Script/20-mousepad.sh"
echo; echo "SUMMARY [$MODN]: PASS: $P  WARN: $W  FAIL: $F"
[ "$F" -eq 0 ] && exit 0 || exit 1; fi
if [ "${1:-}" = undo ]; then
  have_gs && [ "$(gsettings get $SCHEMA $KEY 2>/dev/null)" = "'snow'" ] && gsettings reset $SCHEMA $KEY && ok "Mousepad colour scheme reset"
  rm -f "$OUT" && ok "snow.xml removed"
  [ -f "$CSS" ] && sed -i '/^\/\* snow-mousepad-begin/,/^\/\* snow-mousepad-end/d' "$CSS" && ok "gap block removed from gtk.css"
  exit 0
fi

command -v mousepad >/dev/null 2>&1 || { echo "Installing mousepad (sudo password is asked)..."; sudo apt-get install -y mousepad || { bad "mousepad install failed"; exit 1; }; }
command -v jq >/dev/null 2>&1 || { bad "jq is missing: sudo apt install jq"; exit 1; }
[ -s "$TJ" ] || { bad "$TJ not found (apply a Snow theme first)"; exit 1; }
c() { jq -r ".$1 // empty" "$TJ"; }
BG=$(c bg); SURF=$(c surface); HI=$(c surfaceHi); TXT=$(c text); MUT=$(c muted); ACC=$(c accent); WARN=$(c warn); DNG=$(c danger); OKC=$(c success)
for v in BG SURF HI TXT MUT ACC WARN DNG OKC; do case "${!v}" in "#"[0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F]) ;; *) bad "theme.json: colour $v is missing or not like #rrggbb (got '${!v}')"; exit 1 ;; esac; done

# mix A B PERCENT_OF_A : blends two #rrggbb colours
mix() { local a=${1#\#} b=${2#\#} p=$3 i out=""; for i in 0 2 4; do out+=$(printf '%02x' $(( (0x${a:$i:2} * p + 0x${b:$i:2} * (100 - p)) / 100 ))); done; echo "#$out"; }
SEL=$(mix "$ACC" "$BG" 35); MATCH=$(mix "$ACC" "$BG" 55); LINE=$(mix "$SURF" "$BG" 70)

mkdir -p "$DIR"
cat > "$OUT.new" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by snow-mousepad.sh from ~/.config/snow/state/theme.json. Do not edit by hand: run the script again. -->
<style-scheme id="snow" name="Snow" version="1.0">
  <author>Snow</author>
  <description>Colours follow the Snow theme (one base colour, one accent)</description>

  <color name="bg"      value="$BG"/>
  <color name="surface" value="$LINE"/>
  <color name="hi"      value="$HI"/>
  <color name="fg"      value="$TXT"/>
  <color name="muted"   value="$MUT"/>
  <color name="accent"  value="$ACC"/>
  <color name="sel"     value="$SEL"/>
  <color name="match"   value="$MATCH"/>
  <color name="warn"    value="$WARN"/>
  <color name="danger"  value="$DNG"/>
  <color name="good"    value="$OKC"/>

  <style name="text"                  foreground="fg" background="bg"/>
  <style name="selection"             foreground="fg" background="sel"/>
  <style name="cursor"                foreground="accent"/>
  <style name="secondary-cursor"      foreground="muted"/>
  <style name="current-line"          background="surface"/>
  <style name="line-numbers"          foreground="muted" background="bg"/>
  <style name="current-line-number"   foreground="accent" background="surface" bold="true"/>
  <style name="draw-spaces"           foreground="hi"/>
  <style name="right-margin"          foreground="hi"/>
  <style name="bracket-match"         foreground="fg" background="hi" bold="true"/>
  <style name="bracket-mismatch"      foreground="danger" underline="true"/>
  <style name="search-match"          foreground="bg" background="match"/>

  <style name="def:comment"           foreground="muted" italic="true"/>
  <style name="def:shebang"           foreground="muted" bold="true"/>
  <style name="def:doc-comment-element" foreground="muted" italic="true"/>
  <style name="def:string"            foreground="good"/>
  <style name="def:special-char"      foreground="warn"/>
  <style name="def:character"         foreground="good"/>
  <style name="def:number"            foreground="warn"/>
  <style name="def:constant"          foreground="warn"/>
  <style name="def:special-constant"  foreground="warn"/>
  <style name="def:keyword"           foreground="accent" bold="true"/>
  <style name="def:statement"         foreground="accent"/>
  <style name="def:type"              foreground="warn"/>
  <style name="def:identifier"        foreground="fg"/>
  <style name="def:function"          foreground="accent"/>
  <style name="def:builtin"           foreground="accent"/>
  <style name="def:preprocessor"      foreground="accent"/>
  <style name="def:operator"          foreground="fg"/>
  <style name="def:underlined"        foreground="accent" underline="true"/>
  <style name="def:error"             foreground="danger" bold="true"/>
  <style name="def:warning"           foreground="warn"/>
  <style name="def:note"              foreground="bg" background="warn" bold="true"/>
  <style name="def:heading"           foreground="accent" bold="true"/>
  <style name="def:emphasis"          italic="true"/>
  <style name="def:strong-emphasis"   bold="true"/>
  <style name="def:inline-code"       foreground="good"/>
  <style name="def:link-destination"  foreground="accent" underline="true"/>
</style-scheme>
EOF
command -v xmllint >/dev/null 2>&1 && ! xmllint --noout "$OUT.new" 2>/dev/null && { rm -f "$OUT.new"; bad "the generated XML is not valid: nothing changed"; exit 1; }
mv -f "$OUT.new" "$OUT" && ok "colour scheme written: $OUT (base $BG, accent $ACC)" || { bad "could not write $OUT"; exit 1; }

if have_gs; then
  gsettings set $SCHEMA $KEY snow 2>/dev/null && [ "$(gsettings get $SCHEMA $KEY 2>/dev/null)" = "'snow'" ] && ok "Mousepad now uses the 'Snow' colour scheme" || wr "could not set it automatically: in Mousepad open  View > Color Scheme > Snow"
else wr "Mousepad settings not found: in Mousepad open  View > Color Scheme > Snow"; fi
# gap between line numbers and text (replaces its own old block, keeps the rest of gtk.css)
mkdir -p "$(dirname "$CSS")"; touch "$CSS"
grep -q 'snow-mousepad-begin' "$CSS" || { RB="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)/Docs/logs/replaced/$(date +%Y%m%d-%H%M%S)"; mkdir -p "$RB" && cp -a "$CSS" "$RB/gtk.css"; }   # the old gtk.css is kept inside ~/Snow, never next to the file
sed -i '/^\/\* snow-mousepad-begin/,/^\/\* snow-mousepad-end/d' "$CSS"
cat >> "$CSS" <<EOF
/* snow-mousepad-begin: space between line numbers and text (written by snow-mousepad.sh) */
textview border.left { padding-right: ${GAP}px; }
/* snow-mousepad-end */
EOF
ok "gap of ${GAP}px between line numbers and text written to $CSS"
echo "Close Mousepad completely and open it again to see the colours."
